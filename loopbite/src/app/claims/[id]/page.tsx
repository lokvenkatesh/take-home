import { Suspense } from "react";
import Link from "next/link";
import { notFound } from "next/navigation";
import { and, eq } from "drizzle-orm";
import QRCode from "qrcode";
import { z } from "zod";
import { db } from "@/db";
import { claims, listings, users } from "@/db/schema";
import { requireRole } from "@/lib/auth";
import { AppHeader } from "@/components/AppHeader";
import { LiveTimeTag } from "@/components/LiveTimeTag";
import { PassActions } from "@/components/PassActions";
import { CheckMark } from "@/components/CheckMark";

type Params = Promise<{ id: string }>;

export default function ClaimPage({ params }: { params: Params }) {
  return (
    <Suspense fallback={<p className="p-6">Loading…</p>}>
      <Pass params={params} />
    </Suspense>
  );
}

const STATUS_TEXT = {
  active: "Show this code at the counter to collect your food.",
  picked_up: "Picked up. Enjoy your food.",
  released: "You dropped this pickup, so it went back to other students.",
  no_show: "This pickup was missed.",
} as const;

async function Pass({ params }: { params: Params }) {
  const user = await requireRole("student");
  const { id } = await params;
  if (!z.uuid().safeParse(id).success) notFound();

  // Only the student who owns the claim can see its pass
  const [row] = await db
    .select({ claim: claims, listing: listings, donorName: users.businessName })
    .from(claims)
    .innerJoin(listings, eq(listings.id, claims.listingId))
    .innerJoin(users, eq(users.id, listings.donorId))
    .where(and(eq(claims.id, id), eq(claims.studentId, user.id)))
    .limit(1);
  if (!row) notFound();

  const { claim, listing, donorName } = row;
  const active = claim.status === "active";

  // The QR holds the same code as the text, generated by us, so it's safe to inline
  const qr = active
    ? await QRCode.toString(claim.code, { type: "svg", margin: 1, width: 180, color: { dark: "#17251e", light: "#ffffff" } })
    : null;

  return (
    <>
      <AppHeader name={user.name} role={user.role} />
      <main className="mx-auto max-w-md px-6 py-10">
        <h1 className="font-display text-4xl font-extrabold">
          {active ? "It's yours" : claim.status === "picked_up" ? "Enjoy" : "Pickup pass"}
        </h1>
        <p className="mt-2 text-muted">{STATUS_TEXT[claim.status]}</p>

        {claim.status === "picked_up" && <CheckMark />}

        <section className={`mt-8 rounded-2xl border-2 border-dashed border-ink bg-surface p-6 text-center ${active ? "stamp" : ""}`}>
          {qr && (
            <div
              className="mx-auto mb-4 w-fit rounded-lg bg-white p-2"
              role="img"
              aria-label={`QR code for pickup code ${claim.code}`}
              dangerouslySetInnerHTML={{ __html: qr }}
            />
          )}
          <p className="text-sm text-muted">Pickup code</p>
          <p className={`mt-1 font-display text-5xl font-extrabold tracking-wider ${active ? "" : "text-muted line-through"}`}>
            {claim.code}
          </p>
          {active && (
            <div className="mt-5 flex justify-center">
              <LiveTimeTag expiresAt={listing.pickupEnd.toISOString()} serverNow={Date.now()} />
            </div>
          )}
        </section>

        {active && <PassActions claimId={claim.id} />}

        <section className="mt-8 space-y-1">
          <h2 className="font-display text-xl font-extrabold">{listing.title}</h2>
          <p className="text-muted">{donorName}</p>
          <p>{listing.quantityText}, about {listing.estLbs} lb</p>
          <p className="pt-2 font-bold">{listing.location}</p>
        </section>

        <div className="mt-8 flex gap-4 text-sm font-bold">
          <Link href={`/report/${listing.id}`} className="underline">Report a problem</Link>
          <Link href="/claims" className="underline">All my claims</Link>
          <Link href="/feed" className="underline">Back to food</Link>
        </div>
      </main>
    </>
  );
}
